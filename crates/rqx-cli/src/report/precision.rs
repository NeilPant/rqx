//! `docs/perf-precision.md`: how often the cost analysis and the performance rules were
//! right on the precision corpus, written from the corpus's committed baseline so the
//! numbers on the page are the ones the test gates.

use std::fmt::Write as _;

use rqx_core::precision::{Baseline, RuleCounts, Section, TOTAL, Tally};

/// The languages in the order the rest of the documentation lists them.
const LANGUAGES: [&str; 6] = ["typescript", "javascript", "python", "go", "java", "cpp"];

pub fn page(baseline: &Baseline) -> String {
    let written = baseline.synthetic();
    let mut page = String::from(
        "# Precision of the cost analysis\n\n\
         Generated by `rqx docs` from `fixtures/complexity/baseline.json`.\n\n\
         `rqx perf` reports the order of each function's time and space. This page \
         says how often those orders, and the performance rules that read them, \
         matched what a person worked out by reading the same code.\n",
    );
    page.push_str(&corpus_section(&written, &baseline.real));
    page.push_str(&language_section(
        "Written functions",
        "Functions written for the corpus, covering each loop bound, recurrence shape, \
         library table entry and call depth, with lookalikes that must not be reported.",
        &written,
    ));
    page.push_str(&language_section(
        "Functions from real projects",
        "Functions copied unchanged from open source projects (vite, flask, cobra, gson \
         and fmt). They are scored apart so that the number for real code is not \
         averaged with the number for the functions written for the corpus.",
        &baseline.real,
    ));
    page.push_str(&rule_section(baseline));
    page.push_str(METHOD);
    page.push_str(LIMITS);
    page
}

fn corpus_section(written: &Section, real: &Section) -> String {
    let (written, real) = (written.tallies_by_language(), real.tallies_by_language());
    let mut text = String::from(
        "\n## Corpus size\n\n| Language | Written functions | Real functions |\n|---|---:|---:|\n",
    );
    for language in LANGUAGES {
        let _ = writeln!(
            text,
            "| {} | {} | {} |",
            title(language),
            count(&written, language),
            count(&real, language)
        );
    }
    let _ = writeln!(
        text,
        "| Total | {} | {} |",
        count(&written, TOTAL),
        count(&real, TOTAL)
    );
    text
}

fn count(tallies: &std::collections::BTreeMap<String, Tally>, group: &str) -> usize {
    tallies.get(group).map_or(0, Tally::functions)
}

fn language_section(heading: &str, about: &str, section: &Section) -> String {
    let tallies = section.tallies_by_language();
    let mut text = format!(
        "\n## {heading}\n\n{about}\n\n\
         | Language | Functions | Exact | Over | Under | Abstained | Precision | Recall |\n\
         |---|---:|---:|---:|---:|---:|---:|---:|\n"
    );
    for group in LANGUAGES.into_iter().chain([TOTAL]) {
        let Some(tally) = tallies.get(group) else {
            continue;
        };
        let _ = writeln!(
            text,
            "| {} | {} | {} | {} | {} | {} | {} | {} |",
            title(group),
            tally.functions(),
            tally.exact,
            tally.over,
            tally.under,
            tally.abstained,
            ratio(tally.precision()),
            ratio(tally.recall()),
        );
    }
    text
}

fn rule_section(baseline: &Baseline) -> String {
    let mut text = String::from(
        "\n## Rules\n\n\
         Each rule over the written and the real functions together. A report is right \
         when the function was annotated for the rule, a false alarm when it was not, \
         and a miss is a function annotated for the rule that it did not report. \
         `rqx explain` prints the precision column.\n\n\
         | Rule | Right | False alarms | Missed | Precision | Recall |\n\
         |---|---:|---:|---:|---:|---:|\n",
    );
    for (rule, counts) in baseline.rules_overall() {
        let RuleCounts { tp, fp, missed } = counts;
        let _ = writeln!(
            text,
            "| `{rule}` | {tp} | {fp} | {missed} | {} | {} |",
            ratio(counts.precision()),
            ratio(counts.recall()),
        );
    }
    text
}

fn title(group: &str) -> String {
    match group {
        "typescript" => "TypeScript".to_owned(),
        "javascript" => "JavaScript".to_owned(),
        "python" => "Python".to_owned(),
        "go" => "Go".to_owned(),
        "java" => "Java".to_owned(),
        "cpp" => "C++".to_owned(),
        _ => "Total".to_owned(),
    }
}

fn ratio(value: Option<f64>) -> String {
    value.map_or_else(|| "n/a".to_owned(), |value| format!("{value:.2}"))
}

const METHOD: &str = "
## Method

Every function in the corpus has a comment above it giving the time and space order a \
person worked out from the code, and the performance rules that should and should not \
report on it. The test runs the analysis `rqx perf` runs, extraction of each function \
followed by composition across calls and files, and compares the answer with the \
comment. The answer is exact when both orders are equal once the sizes are named alike, \
over when it is larger, under when it is smaller, and abstained when the analysis \
declined to give an order. Precision is exact answers over answered functions, recall \
is exact answers over all functions. A rule counts as right on a function annotated for \
it, as a false alarm on a function it reports without being annotated for it, and as a \
miss on an annotated function it does not report. Two rules that can both describe a \
call that walks a collection in a loop, `scan-in-loop` and `linear-op-in-loop`, accept \
either report.

The committed baseline records the outcome of every function and the count of every \
rule. The test fails when a function that was exact stops being exact, or when any \
language's precision or recall, or any rule's right, false alarm or missed count, gets \
worse. The baseline changes only when someone rewrites it with `RQX_BLESS=1`, so a \
drop shows in the diff of the commit that causes it. Where the analysis is wrong the \
annotation keeps the true answer and the baseline records the miss.
";

const LIMITS: &str = "
## Limits

The orders are worked out by reading code, not by running it. An empirical harness that \
times a function over a sweep of input sizes and fits the growth would catch an \
annotation that is itself wrong. The optional `tools/perf-validate` harness for this is \
out of scope for this release, so the annotations are not checked by measurement. The \
real sample is small, so one function moves a language by several points. A rule's recall is measured only on \
functions annotated for it, and the corpus does not annotate every function for every \
rule. Rules that the corpus has no annotation for have no row.
";

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use rqx_core::precision::Outcome;

    use super::*;

    fn baseline() -> Baseline {
        let mut baseline = Baseline::of(BTreeMap::from([
            ("python/a.py:f".to_owned(), Outcome::Exact),
            ("python/a.py:g".to_owned(), Outcome::Over),
            ("go/a.go:F".to_owned(), Outcome::Exact),
        ]));
        baseline.rules.insert(
            "scan-in-loop".to_owned(),
            RuleCounts {
                tp: 3,
                fp: 1,
                missed: 2,
            },
        );
        baseline
            .real
            .functions
            .insert("real/go/c.go:H".to_owned(), Outcome::Under);
        baseline.real.rules.insert(
            "scan-in-loop".to_owned(),
            RuleCounts {
                tp: 1,
                fp: 1,
                missed: 0,
            },
        );
        baseline
    }

    #[test]
    fn each_language_is_a_row_with_its_precision_and_recall() {
        let page = page(&baseline());
        assert!(
            page.contains("| Python | 2 | 1 | 1 | 0 | 0 | 0.50 | 0.50 |"),
            "{page}"
        );
        assert!(
            page.contains("| Go | 1 | 1 | 0 | 0 | 0 | 1.00 | 1.00 |"),
            "{page}"
        );
        assert!(
            page.contains("| Total | 3 | 2 | 1 | 0 | 0 | 0.67 | 0.67 |"),
            "{page}"
        );
    }

    #[test]
    fn the_real_functions_have_a_table_of_their_own() {
        let page = page(&baseline());
        assert!(page.contains("## Functions from real projects"), "{page}");
        assert!(
            page.contains("| Go | 1 | 0 | 0 | 1 | 0 | 0.00 | 0.00 |"),
            "{page}"
        );
        assert!(page.contains("| Go | 1 | 1 |"), "the corpus sizes: {page}");
    }

    #[test]
    fn a_rule_is_counted_over_both_sets() {
        let page = page(&baseline());
        assert!(
            page.contains("| `scan-in-loop` | 4 | 2 | 2 | 0.67 | 0.67 |"),
            "{page}"
        );
    }

    #[test]
    fn a_language_with_no_function_has_no_row_and_no_number() {
        let page = page(&baseline());
        assert!(!page.contains("| Java | 1"), "{page}");
        assert_eq!(ratio(None), "n/a");
    }
}
